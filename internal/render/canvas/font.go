func init() {
	glyphs = make(map[rune]glyph, len(fontSrc))
	for r, src := range fontSrc {
		rows := strings.Split(strings.Trim(src, "\n"), "\n")
		var g glyph
		for y := 0; y < GlyphH && y < len(rows); y++ {
			row := rows[y]
			for x := 0; x < GlyphW && x < len(row); x++ {
				if row[x] == '#' {
					g[y] |= 1 << uint(GlyphW-1-x)
				}
			}
		}
		glyphs[r] = g
	}
}

// TextWidth returns the pixel width a string would occupy.
func TextWidth(s string) int {
	n := 0
	for range s {
		n++
	}
	if n == 0 {
		return 0
	}
	return n*AdvanceX - 1 // last glyph has no trailing gap
}

// DrawText bakes s into the canvas at top-left pixel (x, y) in col. Unknown
// runes advance without drawing. Returns the x just past the last glyph.
func (c *Canvas) DrawText(x, y int, s string, col Color) int {
	for _, r := range s {
		g, ok := glyphs[r]
		if ok {
			for gy := 0; gy < GlyphH; gy++ {
				row := g[gy]
				if row == 0 {
					continue
				}
				for gx := 0; gx < GlyphW; gx++ {
					if row&(1<<uint(GlyphW-1-gx)) != 0 {
						c.Set(x+gx, y+gy, col)
					}
				}
			}
		}
		x += AdvanceX
	}
	return x
}

// DrawTextShadow bakes s with a 1px dark drop shadow under it, then the glyph
// in col — keeping text readable over busy pixels (the old glyph layer leaned
// on an opaque black backing for the same reason).
func (c *Canvas) DrawTextShadow(x, y int, s string, col, shadow Color) {
	c.DrawText(x+1, y+1, s, shadow)
	c.DrawText(x, y, s, col)
}
